//! SM2 curve (GB/T 32918-2016).
//!
//! SM2 has no standardized hash-to-curve suite. We define one following the
//! RFC 9380 recipe, analogous to `P256_XMD:SHA-256_SSWU_RO_`:
//!
//! - suite ID `SM2_XMD:SM3_SSWU_RO_`
//! - `expand_message_xmd` with SM3, `k = 128`, `L = 48`
//! - Simplified SWU directly on the curve (`A = -3`, `B != 0`, no isogeny)
//! - `Z = -9`, the value selected by RFC 9380 Appendix H.2 for SM2
//! - cofactor `h = 1`, so no clearing
//!
//! It only interoperates with implementations of this exact suite.

use ::sm3::Sm3;
use hash2curve::ExpandMsgXmd;
use primeorder::elliptic_curve::consts::U16;
use primeorder::elliptic_curve::ff::{Field, PrimeField};
use primeorder::elliptic_curve::hazmat::FieldArithmetic;
use primeorder::elliptic_curve::sec1::FromSec1Point;
use primeorder::elliptic_curve::Generate;
use primeorder::PrimeCurveParams;
use rand::CryptoRng;
use sm2::{AffinePoint, NonZeroScalar, ProjectivePoint, Scalar};

use super::hash_to_curve::{expand_message, map_to_curve_sswu, reduce_48, SswuParams};
use super::{decode_sec1, encode_sec1, Group};
use crate::primitives::hash::sm3;
use crate::Result;

type Fe = <sm2::Sm2 as FieldArithmetic>::FieldElement;

/// SSWU parameters for SM2.
fn sswu_params() -> SswuParams<Fe> {
    SswuParams {
        a: <sm2::Sm2 as PrimeCurveParams>::EQUATION_A,
        b: <sm2::Sm2 as PrimeCurveParams>::EQUATION_B,
        z: -Fe::from(9u64),
        // (p - 3) / 4
        c1: [
            0x3fff_ffff_ffff_ffff,
            0xffff_ffff_c000_0000,
            0xffff_ffff_ffff_ffff,
            0x3fff_ffff_bfff_ffff,
        ],
        // sqrt(-Z) = sqrt(9)
        c2: Fe::from(3u64),
    }
}

/// Affine `(x, y)` known to be on the curve to a point.
fn point(x: Fe, y: Fe) -> ProjectivePoint {
    let mut sec1 = [0u8; 65];
    sec1[0] = 0x04;
    sec1[1..33].copy_from_slice(&x.to_repr());
    sec1[33..].copy_from_slice(&y.to_repr());
    AffinePoint::from_sec1_bytes(&sec1)
        .expect("SSWU output lies on the curve")
        .into()
}

/// SM2 with the `SM2_XMD:SM3_SSWU_RO_` hash-to-curve suite (see module docs).
pub(crate) struct Sm2;

impl Group for Sm2 {
    type Scalar = Scalar;
    type Point = ProjectivePoint;

    const POINT_LEN: usize = 33;
    const SUITE_ID: &'static [u8] = b"SM2_XMD:SM3_SSWU_RO_";

    fn random_scalar<R: CryptoRng + ?Sized>(rng: &mut R) -> Scalar {
        *NonZeroScalar::generate_from_rng(rng)
    }

    fn hash_to_group(msg: &[u8], dst: &[&[u8]]) -> ProjectivePoint {
        let params = sswu_params();
        let mut uniform = [0u8; 96];
        expand_message::<ExpandMsgXmd<Sm3>, U16>(&[msg], dst, &mut uniform);
        let u0: Fe = reduce_48(uniform[..48].try_into().expect("48 bytes"));
        let u1: Fe = reduce_48(uniform[48..].try_into().expect("48 bytes"));
        let (x0, y0) = map_to_curve_sswu(&params, &u0);
        let (x1, y1) = map_to_curve_sswu(&params, &u1);
        point(x0, y0) + point(x1, y1)
    }

    fn mul(p: &ProjectivePoint, k: &Scalar) -> ProjectivePoint {
        *p * k
    }

    fn invert(k: &Scalar) -> Scalar {
        Option::from(<Scalar as Field>::invert(k)).expect("non-zero scalar")
    }

    fn encode(p: &ProjectivePoint, out: &mut [u8]) {
        encode_sec1(p, out);
    }

    fn decode(bytes: &[u8]) -> Result<ProjectivePoint> {
        decode_sec1(bytes)
    }

    fn hash(parts: &[&[u8]]) -> [u8; 32] {
        sm3(parts)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn params_are_consistent() {
        let p = sswu_params();
        assert_eq!(p.c2.square(), -p.z);
        // x^(4 c1 + 3) = x^p = x, so the limbs encode (p - 3) / 4.
        let x = Fe::from(987_654_321u64);
        let y = <Fe as Field>::pow_vartime(&x, p.c1);
        assert_eq!(y.square().square() * x.square() * x, x);
        // Z must be a non-square.
        assert!(bool::from(<Fe as Field>::sqrt(&p.z).is_none()));
    }

    /// Vectors for `SM2_XMD:SM3_SSWU_RO_`, generated by an independent
    /// straight-line Python implementation of RFC 9380 (itself checked
    /// against the RFC's P-256 vectors). DST follows the RFC test convention.
    #[test]
    fn suite_test_vectors() {
        use crate::primitives::test_util::hex;
        use primeorder::elliptic_curve::sec1::ToSec1Point;

        let a512 = [&b"a512_"[..], &[b'a'; 507]].concat();
        let vectors: [(&[u8], &str, &str); 4] = [
            (
                b"",
                "80048bf6454de460598966bc3bc9a3213e8776668817d85cf447eda370991a41",
                "cf41fd9fa681d1416ddb5129e570bef4d74c4e0c1a5be8009717eb1c02e8e9e9",
            ),
            (
                b"abc",
                "7cf8871dffcb584997d9b27cbc1b12308eec4544f38688f7b8c53531afb9fdcd",
                "e803123cc855d859d58857cbea53c0cf0187b160e3a4996a9260879a1b059203",
            ),
            (
                b"abcdef0123456789",
                "9fbfac2f80e2492165c664f1329a2e8391d39ec33e6c7a57c0e582d17e533c0e",
                "733e1148256a3fcb971b89789755fd8e8c292b7e82a67ab38c46a827b6cacc0b",
            ),
            (
                &a512,
                "e3d50dc7dbb70aa8d8a60a530c15c915b46cd11b112c27621d2f1ea129849113",
                "687b002c604416e61b1bf843615edd998bac8416b662ee610e616b3657a6e3ea",
            ),
        ];
        let dst: &[&[u8]] = &[b"QUUX-V01-CS02-with-", Sm2::SUITE_ID];
        for (msg, x, y) in vectors {
            let p = Sm2::hash_to_group(msg, dst)
                .to_affine()
                .to_sec1_point(false);
            let mut expected = vec![0x04];
            expected.extend(hex(x));
            expected.extend(hex(y));
            assert_eq!(p.as_bytes(), expected.as_slice(), "msg len {}", msg.len());
        }
    }

    #[test]
    fn sswu_output_is_on_curve() {
        // `point` checks the curve equation; exercise many field elements,
        // including the exceptional u = 0 (tv2 == 0) case.
        let params = sswu_params();
        for i in 0..64u64 {
            let (x, y) = map_to_curve_sswu(&params, &Fe::from(i));
            point(x, y);
        }
    }
}
